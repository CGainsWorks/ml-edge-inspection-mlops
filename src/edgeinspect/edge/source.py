"""Frame sources: what stands in for the camera.

A real deployment reads a GigE Vision or CSI camera.  This project has no
camera, so the production stream is generated by the same physically
parameterised model the training set came from, under *different* imaging
conditions and with a *different* random stream.  That is the honest version of
a simulated line: the pixels are synthetic in both cases, and the shift between
them is a stated change in imaging conditions rather than a different random
seed dressed up as drift.

:class:`StreamSpec` is read from the ``streams`` block of ``configs/data.yaml``.
A stream is either a fixed domain or a linear ramp between two, because the two
have completely different detection characteristics: a step change is caught by
anything, and a ramp is what actually happens when a lamp ages.
"""

from __future__ import annotations

from dataclasses import dataclass
from typing import Iterator, Optional, Tuple

import numpy as np

from ..config import DomainSpec
from ..data import synth
from ..data.dataset import Record, load_index, read_png


@dataclass(frozen=True)
class StreamSpec:
    """One production stream: how long, under what conditions, drifting how."""

    name: str
    domain: DomainSpec
    frames: int
    to_domain: Optional[DomainSpec] = None
    ramp_start: int = 0
    ramp_end: int = 0
    defect_rate: float = 0.08
    seed: int = 991

    def domain_at(self, frame_id: int) -> DomainSpec:
        """The imaging conditions in force at ``frame_id``."""
        base = self.domain
        if self.to_domain is None:
            return base
        if frame_id <= self.ramp_start:
            alpha = 0.0
        elif frame_id >= self.ramp_end:
            alpha = 1.0
        else:
            span = max(self.ramp_end - self.ramp_start, 1)
            alpha = (frame_id - self.ramp_start) / span
        if alpha <= 0.0:
            return base
        return base.blend(self.to_domain, alpha)

    @property
    def onset(self) -> Optional[int]:
        """The frame at which conditions start to move, or ``None`` if they never do."""
        return self.ramp_start if self.to_domain is not None else None

    @classmethod
    def from_config(cls, name: str, spec: dict, domains: dict,
                    seed: int = 991) -> "StreamSpec":
        base_name = spec.get("domain", "reference")
        if base_name not in domains:
            raise ValueError(
                "stream {0!r} references unknown domain {1!r}.  Known: {2}".format(
                    name, base_name, sorted(domains))
            )
        target_name = spec.get("to")
        if target_name is not None and target_name not in domains:
            raise ValueError(
                "stream {0!r} ramps to unknown domain {1!r}".format(name, target_name)
            )
        return cls(
            name=name,
            domain=domains[base_name],
            frames=int(spec["frames"]),
            to_domain=domains[target_name] if target_name else None,
            ramp_start=int(spec.get("ramp_start", 0)),
            ramp_end=int(spec.get("ramp_end", 0)),
            defect_rate=float(spec.get("defect_rate", 0.08)),
            seed=int(spec.get("seed", seed)),
        )


class SyntheticCamera:
    """Generates a production stream frame by frame.

    The seed for frame *n* is a hash of ``(stream seed, stream name, n)``, so a
    stream is reproducible, resumable from any point, and independent of the
    domains it passes through -- which means the clean and drifted streams
    contain *different* parts rather than the same parts relit.  Relighting the
    same parts would make the drift trivially separable and the experiment
    worthless.
    """

    def __init__(self, spec: StreamSpec, image_size: int = synth.IMAGE_SIZE,
                 with_masks: bool = True):
        self.spec = spec
        self.image_size = int(image_size)
        self.with_masks = bool(with_masks)

    def __len__(self) -> int:
        return int(self.spec.frames)

    def __iter__(self) -> Iterator[Tuple[int, np.ndarray, Optional[np.ndarray], int, str]]:
        for frame_id in range(self.spec.frames):
            yield self.frame(frame_id)

    def frame(self, frame_id: int):
        """Return ``(frame_id, image, mask, label, domain_name)``.

        ``image`` is float32 ``(1, H, W)`` in ``[0, 1]``, matching the graph
        input, and ``mask`` is ``(1, H, W)`` or ``None``.
        """
        domain = self.spec.domain_at(frame_id)
        seed = synth.frame_seed(self.spec.seed, self.spec.name, frame_id, self.spec.domain.name)
        rng = np.random.default_rng(seed ^ 0x5DEECE66D)
        force = 1 if rng.random() < self.spec.defect_rate else 0
        generated = synth.generate_frame(seed, domain, size=self.image_size, force_label=force)
        image = (generated.image.astype(np.float32) / 255.0)[None, :, :]
        mask = None
        if self.with_masks:
            mask = (generated.mask.astype(np.float32) / 255.0)[None, :, :]
        return frame_id, image, mask, generated.label, domain.name


class DatasetSource:
    """Replays an on-disk split as a stream.  Used for benchmarking and evaluation."""

    def __init__(self, data_root, split: str, records: Optional[list] = None,
                 name: Optional[str] = None):
        self.records: list[Record] = list(records) if records else load_index(data_root, split)
        self.name = name or split

    def __len__(self) -> int:
        return len(self.records)

    def __iter__(self):
        from .. import paths as _paths

        for frame_id, record in enumerate(self.records):
            image = read_png(_paths.resolve(record.image)).astype(np.float32) / 255.0
            mask = read_png(_paths.resolve(record.mask)).astype(np.float32) / 255.0
            yield frame_id, image[None, :, :], mask[None, :, :], record.label, record.domain
